def main():
    items = []
    for i, (theme, text, source) in enumerate(QUOTES, 1):
        items.append({
            "id": "q%03d" % i,
            "kind": "quote",
            "theme": theme,
            "text": text,
            "source": source
        })
    for i, (theme, text, meaning) in enumerate(IDIOMS, 1):
        items.append({
            "id": "i%03d" % i,
            "kind": "idiom",
            "theme": theme,
            "text": text,
            "meaning": meaning
        })
    out = {
        "version": "20261122A",
        "updated": "2026-11-22",
        "count": len(items),
        "quoteCount": len(QUOTES),
        "idiomCount": len(IDIOMS),
        "items": items
    }
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    path = os.path.join(root, "wordbank.json")
    with io.open(path, "w", encoding="utf-8", newline="\n") as f:
        json.dump(out, f, ensure_ascii=False, indent=1)
        f.write("\n")
    print("wrote", path, "quotes", len(QUOTES), "idioms", len(IDIOMS), "total", len(items))


if __name__ == "__main__":
    main()
